CREATE TABLE IF NOT EXISTS access_presets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  description TEXT,
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS access_preset_subcategory (
  preset_id BIGINT NOT NULL REFERENCES access_presets(id) ON DELETE CASCADE,
  subcategory_id TEXT NOT NULL,
  PRIMARY KEY (preset_id, subcategory_id)
);

CREATE TABLE IF NOT EXISTS access_preset_override (
  preset_id BIGINT NOT NULL REFERENCES access_presets(id) ON DELETE CASCADE,
  report_id TEXT NOT NULL,
  effect TEXT NOT NULL CHECK (effect IN ('allow', 'deny')),
  PRIMARY KEY (preset_id, report_id)
);

CREATE TABLE IF NOT EXISTS report_catalog_state (
  report_id TEXT PRIMARY KEY,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  updated_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  updated_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS activity_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  action TEXT NOT NULL,
  target_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  report_id TEXT,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_activity_log_created_at
  ON activity_log(created_at DESC);

CREATE INDEX IF NOT EXISTS idx_activity_log_user_id
  ON activity_log(user_id);

CREATE INDEX IF NOT EXISTS idx_activity_log_action
  ON activity_log(action);