CREATE TABLE IF NOT EXISTS user_subcategory_access (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  subcategory_id TEXT NOT NULL,
  granted_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  UNIQUE (user_id, subcategory_id)
);

CREATE INDEX IF NOT EXISTS idx_user_subcategory_access_user
  ON user_subcategory_access(user_id);

CREATE TABLE IF NOT EXISTS user_report_override (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  report_id TEXT NOT NULL,
  effect TEXT NOT NULL CHECK (effect IN ('allow', 'deny')),
  granted_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  UNIQUE (user_id, report_id)
);

CREATE INDEX IF NOT EXISTS idx_user_report_override_user
  ON user_report_override(user_id);

CREATE INDEX IF NOT EXISTS idx_user_report_override_report
  ON user_report_override(report_id);

